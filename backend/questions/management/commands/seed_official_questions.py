class Command(BaseCommand):
    help = "Наповнення бази даних офіційними екзаменаційними питаннями ПДР України з варіантами відповідей"

    def handle(self, *args, **options):
        self.stdout.write("Ініціалізація банку офіційних питань ПДР України...")
        created_count = 0
        updated_count = 0

        with transaction.atomic():
            for item in OFFICIAL_QUESTIONS_DATA:
                section = RuleSection.objects.filter(number=item["section_number"]).first()
                if not section:
                    self.stdout.write(
                        self.style.WARNING(
                            f"Розділ № {item['section_number']} не знайдено, пропускаємо питання: {item['text'][:40]}"
                        )
                    )
                    continue

                question, created = Question.objects.get_or_create(
                    text=item["text"],
                    defaults={
                        "section": section,
                        "explanation": item["explanation"],
                        "difficulty": item["difficulty"],
                        "question_type": Question.QuestionType.OFFICIAL,
                        "ai_status": Question.AIStatus.APPROVED,
                        "is_active": True,
                    },
                )

                if created:
                    created_count += 1
                else:
                    updated_count += 1
                    question.section = section
                    question.explanation = item["explanation"]
                    question.difficulty = item["difficulty"]
                    question.is_active = True
                    question.ai_status = Question.AIStatus.APPROVED
                    question.save()

                # Link points
                for pt_num in item.get("points", []):
                    pt = RulePoint.objects.filter(number=pt_num).first()
                    if pt:
                        question.rule_points.add(pt)

                # Answers options
                existing_options = {opt.text: opt for opt in question.answers.all()}
                for idx, (opt_text, is_corr) in enumerate(item["options"]):
                    if opt_text in existing_options:
                        opt = existing_options[opt_text]
                        opt.is_correct = is_corr
                        opt.order = idx
                        opt.save()
                    else:
                        AnswerOption.objects.create(
                            question=question,
                            text=opt_text,
                            is_correct=is_corr,
                            order=idx,
                        )

        self.stdout.write(
            self.style.SUCCESS(
                f"Успішно імпортовано офіційні питання: {created_count} створено, {updated_count} оновлено. "
                f"Всього питань у базі: {Question.objects.count()}."
            )
        )
